import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

export const root = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..');
export const docs = resolve(root, 'site/src/content/docs/docs');
export const read = (p) => readFileSync(resolve(root, p), 'utf8');
export function write(rel, text) {
  const p = resolve(root, rel);
  mkdirSync(dirname(p), { recursive: true });
  writeFileSync(p, text);
}
/** Runs `fluxwire reference <what>` (needs a Rust toolchain; CI checks the committed output is fresh). */
export function reference(what) {
  return execFileSync('cargo', ['run', '-q', '-p', 'fluxwire-cli', '--', 'reference', what], {
    cwd: root, encoding: 'utf8', maxBuffer: 1 << 24,
  });
}
export const banner = (src) => `{/* Generated by site/scripts from ${src}. Do not edit by hand. */}\n`;
